def compose_reply(sc, lang, i):
    opener = random.choice(OPENERS[lang])
    val = random.choice(VALIDATE)
    bridge = random.choice(sc["bridges"])
    q = random.choice(sc["qs"])
    return f"{opener}{val} {bridge} {q}".strip()


def ex(*turns):
    return {"messages": [{"role": "system", "content": SYSTEM_PROMPT}] +
            [{"role": r, "content": c} for r, c in turns]}


